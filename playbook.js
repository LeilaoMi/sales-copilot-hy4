  function defaultScripts() {
    return SEED.map(([category, title, tags, content]) => ({
      id: 'sc-' + Math.random().toString(36).slice(2, 10),
      category: category,
      title: title,
      tags: tags,
      content: content,
      builtin: true,
      source: 'builtin',
      updatedAt: Date.now()
    }));
  }

  /* =============================================================
   * 战后沉淀：把打完的一仗变成自己的话术
   *
   * 这是整个话术库真正有价值的地方 —— 一万条别人的话术，
   * 不如你自己攒的二十条。因为只有你知道你的行业、你的产品、
   * 你的客户会怎么怼你。
   * ============================================================= */
  function extractFromDeal(deal, customer, followups) {
    const f = (followups || [])
      .filter(x => x.dealId === deal.id || (!x.dealId && x.customerId === deal.customerId))
      .slice(-8);
    /* 字段名是 content 不是 note。写错成 note 的时候，notes 恒为空数组，
     * 这个函数三年如一日地返回 null —— 战后沉淀从来没生效过，
     * 而因为没有报错，谁也没发现。字段对不上是最难查的一类 bug。 */
    const notes = f.map(x => String(x.content || '')).filter(Boolean);
    if (!notes.length) return null;

    const all = notes.join('\n');
    const intents = Object.keys(intentsOf(all));

    const lines = all.split(/[\n。！？；]/).map(s => s.trim()).filter(s => s.length >= 6 && s.length <= 120);

    /* 候选一：带引号的原话。
     * 这是跟进记录里最值钱的东西 —— 「王总说：你们比另外那家贵了三成」
     * 一句客户原话，胜过你写十句方法论。所以优先挑它。 */
    const quoted = [];
    (all.match(/[“"'"「『]([^”"'"」』]{4,80})[”"'"」』]/g) || []).forEach(m => {
      const t = m.replace(/^[“"'"「『]|[”"'"」』]$/g, '').trim();
      if (t.length >= 4) quoted.push(t);
    });

    /* 候选二：命中异议/意图词典的叙述句 */
    const byIntent = lines.filter(l => Object.keys(intentsOf(l)).length > 0);

    /* 原话在前，叙述在后，去重。
     * 上限 6 句：再多就不是话术是流水账了 */
    const seen = {};
    let cand = quoted.concat(byIntent).filter(l => {
      const k = l.replace(/\s/g, '');
      if (seen[k] || k.length < 4) return false;
      seen[k] = 1;
      return true;
    });

    /* 去掉被别的候选整句包含的那些。
     * 「你们比另外那家贵了三成」和「王总说『你们比另外那家贵了三成』，
     * 我把 ROI 测算口径讲了一遍」会同时入选，存进去就是一句废话重复两遍。
     * 留短的那句：长句里往往混着销售自己做了什么，
     * 那不是可复用的话术，是流水账。 */
    cand = cand.filter(longer => !cand.some(shorter =>
      shorter !== longer && longer.indexOf(shorter) >= 0 && longer.length > shorter.length
    ));

    cand = cand.slice(0, 6);

    if (!cand.length) return null;

    const label = intentLabel(intents.slice(0, 2)) || '实战记录';
    const stage = { lead: '线索', contact: '需求沟通', solution: '方案', quote: '报价', negotiate: '谈判', won: '赢单', lost: '输单' }[deal.stage] || '跟进';

    /* 标题里带「赢/输」，是因为这两种经验的用法完全不同：
     * 赢单的经验是「照着再做一遍」，输单的经验是「下次别这么干」。
     * 混在一起存，三个月后翻出来根本不知道该学还是该避。 */
    return {
      category: deal.stage === 'won' ? '赢单复盘' : deal.stage === 'lost' ? '输单复盘' : '我的实战',
      title: (customer && customer.name ? customer.name : '某客户') + ' · ' + stage + ' · ' + label,
      /* 存中文标签而不是 'price' 这种内部槽名：
       * 一、用户可以看懂并且自己改；
       * 二、检索是按中文切词的，存英文 key 等于给这条话术挂了个谁也搜不到的标签 */
      tags: intents.slice(0, 3).map(k => intentLabel([k]) || k),
      content: cand.slice(0, 5).join('\n'),
      source: deal.stage === 'won' ? 'won' : deal.stage === 'lost' ? 'lost' : 'deal',
      builtin: false,
      fromDealId: deal.id,
      fromCustomer: (customer && customer.name) || ''
    };
  }

  return { tokens: tokens, bag: bag, search: search, intentsOf: intentsOf, intentLabel: intentLabel,
    defaultScripts: defaultScripts, extractFromDeal: extractFromDeal, tagText: tagText, SEED: SEED };
