  /* 反向索引：词 → 意图槽，避免每次检索都全表扫词典 */
  const WORD2INTENT = (function () {
    const m = Object.create(null);
    Object.keys(INTENT).forEach(k => {
      INTENT[k].forEach(w => {
        const lw = String(w).toLowerCase();
        (m[lw] || (m[lw] = [])).push(k);
      });
    });
    return m;
  })();

  /* 从一段话里识别出意图槽（可能多个） */
  function intentsOf(text) {
    const str = String(text || '').toLowerCase();
    const hit = Object.create(null);
    Object.keys(WORD2INTENT).forEach(w => {
      if (w.length < 1) return;
      if (str.indexOf(w) >= 0) WORD2INTENT[w].forEach(k => { hit[k] = (hit[k] || 0) + w.length; });
    });
    return hit;
  }

  /* ---------- IDF：逆文档频率 ----------
   * 没有这一步，检索就是一塌糊涂：一个「贵」字在十条话术里都有，
   * 它和「嫌」这种真正的区分词被同等对待，结果就是长得越长、
   * 塞的词越多的话术越容易命中 —— 实测里「输单复盘」那两条
   * 就是靠这个污染了价格、决策、竞品三类查询。
   * IDF 让常见字自我降权，罕见词自动上位。 */
  const idfCache = { list: null, len: -1, idf: null };
  /* tags 在库里有两种写法：内置种子是数组，用户在表单里手填的是「逗号分隔的字符串」。
   * 两种都得认 —— 只认数组的话，用户自己新建一条带关键词的话术，
   * 下次他搜索的时候整个检索就崩了，而且正好崩在他最需要搜到它的那一刻。
   * 顺手把各种分隔符统一换成空格，免得 bigram 切出「贵，」「，嫌」这种垃圾片段。 */
  function tagText(s) {
    const t = s && s.tags;
    if (Array.isArray(t)) return t.join(' ');
    return String(t || '').replace(/[,，、;；|]/g, ' ');
  }

  function buildIdf(list) {
    if (idfCache.list === list && idfCache.len === list.length) return idfCache.idf;
    const df = Object.create(null);
    let n = 0;
    (list || []).forEach(s => {
      n++;
      const t = {};
      tokens([s.title, s.content, tagText(s)].join(' ')).forEach(w => { t[w] = 1; });
      Object.keys(t).forEach(w => { df[w] = (df[w] || 0) + 1; });
    });
    const idf = Object.create(null);
    const N = Math.max(1, n);
    for (const k in df) idf[k] = Math.log(1 + N / (1 + df[k]));
    idfCache.list = list; idfCache.len = (list || []).length; idfCache.idf = idf;
    return idf;
  }

  /* 语料里没出现过的词（往往是用户打错或很新的说法）给默认权重，
   * 不能给 0 —— 否则整条 query 的范数塌掉，反而什么都搜不出来 */
  const DEFAULT_IDF = 1.6;

  /* ---------- 相似度：IDF 加权余弦 ---------- */
  function cosine(a, b, idf) {
    let dot = 0, na = 0, nb = 0;
    for (const k in a) {
      const w = idf[k] || DEFAULT_IDF;
      const v = a[k] * w;
      na += v * v;
      if (b[k]) dot += v * (b[k] * w);
    }
    for (const k in b) {
      const w = idf[k] || DEFAULT_IDF;
      const v = b[k] * w;
      nb += v * v;
    }
    if (!na || !nb) return 0;
    return dot / Math.sqrt(na * nb);
  }

  /* ---------- 意图交集 ----------
   * dilute=true 时按「文档命中了多少个意图槽」稀释。
   * 内容越长、涉及面越广的话术（比如复盘类），稀释越狠 ——
   * 它不该在每个查询里都冒头。 */
  function intentOverlap(qIntents, sIntents, dilute) {
    const qk = Object.keys(qIntents);
    if (!qk.length) return { score: 0, keys: [] };
    const keys = [];
    qk.forEach(k => { if (sIntents[k]) keys.push(k); });
    if (!keys.length) return { score: 0, keys: [] };
    let sc = keys.length / qk.length;
    if (dilute) {
      /* 命中 3 个槽以内是正常的 —— 一条话术本来就会牵扯价格、成本、风险好几个面。
       * 只有明显「什么都沾」的（复盘类能命中 8 个槽）才罚，而且用对数平缓惩罚，
       * 别把内容丰富的话术一起打死。 */
      const n = Object.keys(sIntents).length;
      if (n > 3) sc = sc / (1 + Math.log(n - 2));
    }
    return { score: Math.min(1, sc), keys: keys };
  }

  /* ---------- 话术特征缓存 ----------
   * 分词和意图识别跟查询无关，没必要每次按键重算。
   * 缓存在话术对象上，用 updatedAt 判定失效 —— 改完话术自然重算，
   * 不需要额外写失效逻辑。
   *
   * 注意必须用 enumerable:false：否则 JSON.stringify 会把这堆分词结果
   * 一起塞进同步包，每条话术多出几十倍体积，同步直接被拖垮。 */
  function featOf(s) {
    const c = s.__pb;
    if (c && c.at === s.updatedAt) return c;
    const title = String(s.title || '');
    const content = String(s.content || '');
    const tags = tagText(s);
    const text = [title, content, tags].join(' ');
    const f = {
      at: s.updatedAt,
      text: text,
      textLower: text.toLowerCase(),
      titleLower: title.toLowerCase(),
      tagLower: tags.toLowerCase(),
      bag: bag(text),
      nearIntents: intentsOf(title + ' ' + tags),
      farIntents: intentsOf(content)
    };
    try {
      Object.defineProperty(s, '__pb', {
        value: f, enumerable: false, configurable: true, writable: true
      });
    } catch (e) { /* 对象被冻结时跳过缓存，功能不受影响 */ }
    return f;
  }

  /* =============================================================
   * 检索主函数
   *   query  用户输入的任意描述（可以是一整句客户原话）
   *   opts   { limit, category, onlyUser }
   * 返回 [{ s, score, why }]，why 用于给用户看「为什么命中这条」
   * ============================================================= */
  function search(list, query, opts) {
    opts = opts || {};
    const q = String(query || '').trim();
    if (!q) return [];

    const idf = buildIdf(list);
    const qBag = bag(q);
    const qIntent = intentsOf(q);
    const limit = opts.limit || 8;
    const qLower = q.toLowerCase();
    /* 查询是不是在描述一个「客户抛过来的难题」。
     * 是的话，优先给应对类话术 —— 见下面的「困境优先」 */
    const isTrouble = /(不够|没|不|太|别|难|麻烦|怕|担心|拒绝|拖|失联|投诉|贵|砍|压|犹豫|赊|超|骗)/.test(q);
    /* 查询侧的 token / 片段只算一次，别在每条话术的循环里重复切 */
    const qTokens = tokens(q);
    const qFrags = q.match(/[一-龥]{2,}/g) || [];

    const scored = [];
    (list || []).forEach(s => {
      if (opts.category && s.category !== opts.category) return;
      if (opts.onlyUser && s.builtin) return;

      /* 话术侧的分词和意图跟查询无关，没必要每次按键重算一遍。
       * 缓存在对象上，用 updatedAt 判定失效 —— 用户改完话术它自然重算，
       * 不需要额外的失效逻辑。话术攒到几百条时这一步能差出十倍。 */
      const F = featOf(s);

      /* ① 意图分分两层取：
       *    tags + 标题 是「这条话术解决什么问题」的标注，准，占 0.7
       *    正文 是推断出来的 —— 写得长的话术什么都沾一点（复盘类最典型），
       *    所以只占 0.3 且按命中槽数稀释 */
      const near = intentOverlap(qIntent, F.nearIntents, false);
      const far = intentOverlap(qIntent, F.farIntents, true);
      const intentScore = near.score * 0.7 + far.score * 0.3;
      const hitIntent = near.keys.length ? near.keys : far.keys;

      /* ② 字面 bigram 余弦，IDF 加权 */
      const biScore = cosine(qBag, F.bag, idf);

      /* ③ 全文/标题直接命中：保证「照着标题搜」必中 */
      let textScore = 0;
      if (F.titleLower.indexOf(qLower) >= 0) textScore = 1;
      else {
        // 查询里每个 >=2 字的中文片段都出现过就给分
        if (qFrags.length) {
          const ok = qFrags.filter(f => F.text.indexOf(f) >= 0).length;
          textScore = ok / qFrags.length;
        } else if (F.textLower.indexOf(qLower) >= 0) {
          textScore = 0.8;
        }
      }

      /* ④ tags 字面命中。
       * 意图槽是粗粒度的：「太贵了」和「报价后不要急着说话」都属于价格槽，
       * 槽级别的信息到这里就用尽了，必须再往下走一层 —— 比核心词。
       * tags 是人工标的核心词（贵 / 账期 / 失联），字面命中比从正文推断靠谱。 */
      let tagScore = 0;
      if (F.tagLower) {
        let hit = 0;
        qTokens.forEach(t => { if (F.tagLower.indexOf(t) >= 0) hit++; });
        if (hit) tagScore = Math.min(1, hit / Math.max(2, Math.min(4, qTokens.length * 0.5)));
      }

      /* 四路加权。意图权重最高，因为销售搜的是「场景」不是「句子」 */
      let score = intentScore * 0.40 + biScore * 0.30 + textScore * 0.15 + tagScore * 0.15;

      /* 困境优先 —— 这是产品判断，不是技术调参。
       * 查询描述「客户抛过来的难题」（不够/太贵/没预算/怕麻烦/拖着不签…）时，
       * 提问的人多半此刻正站在客户面前，他要的是「下一句说什么」，
       * 不是「下次怎么摸预算」这类方法论。所以应对类话术优先。 */
      if (isTrouble && s.category === '异议处理') score += 0.07;

      /* 标题命中额外加权：标题是话术的主题，比正文更能代表意图 */
      if (F.titleLower.indexOf(qLower) >= 0) score += 0.25;

      /* 用户自己的话术小幅加权 —— 自己的经验永远比通用库更贴自己的行业 */
      if (!s.builtin) score += 0.05;

      /* 沉淀自「赢单」的话术再加权一点：这是验证过能打赢的 */
      if (s.source === 'won') score += 0.04;

      if (score > 0.05) {
        scored.push({
          s: s,
          score: score,
          why: hitIntent.length ? '命中场景：' + intentLabel(hitIntent.slice(0, 2)) : '内容相关'
        });
      }
    });

    scored.sort((a, b) => b.score - a.score);

    /* 只留「够格」的结果，不要硬凑。
     * 不做这一步的话，搜一个库里压根没有的场景，也会返回一堆勉强沾边的 ——
     * 那比直接说「库里没有，记一条吧」更坑：他会把 8 条都翻一遍才发现没用。
     *
     * 门槛分两种，因为信号强度完全不一样：
     *   能识别出场景（嫌贵 / 要账期 / 要招标）→ 语义靠得住，门槛宽松，取最高分 25%
     *   一个场景词都认不出来 → 只剩字面重合，噪声极大（实测「客户说了句没见过的话」
     *   能靠「客户」两个字撑到 0.13 分），门槛必须收到 0.2 */
    if (!scored.length) return [];
    const qIntentKeys = Object.keys(qIntent);
    const gate = qIntentKeys.length
      ? Math.max(0.12, scored[0].score * 0.25)
      : Math.max(0.2, scored[0].score * 0.6);
    return scored.filter(x => x.score >= gate).slice(0, limit);
  }

